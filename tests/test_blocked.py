"""A firewall that stops the check, the one-line summary, and the same finding on two hosts.

When a firewall stops this check it stops this machine too: the answer says so, shows the
proof (the status, the challenge's mark, the firewall its own headers name) and the commands
to see the details from a machine it lets through. Never a disguised User-Agent. The summary
names the platform or language first, then the server, the host and the CDN; every summary
in the corpus is in the table below. The same finding on two hosts is one card listing both.
"""
from __future__ import annotations

import re
import unittest

import php2shell_check as p2s
from tests.helpers import PUBLIC, Net, case_names, case_net, evidenced, run
from tests.test_cli import fixture

MANUAL = 'curl -sI https://{}/ | grep -iE "server|x-powered-by"'
SUMMARY = ("Your site's firewall stopped this check from this machine, so we can't see what it shows. "
           "That's often good news: it blocks automated scanners too.")
NEXT = ("To see the details, run it from a machine the firewall lets through (your office network, or "
        "the server itself), or check by hand:")


def home(page, host="www.example.com"):
    return run(host, Net(names={host: [PUBLIC]}, pages={f"https://{host}/": page}))


class Blocked(unittest.TestCase):
    def assert_blocked(self, got, host, firewalls, marks):
        evidenced(self, got)
        self.assertFalse(got["reached"])
        self.assertEqual(got["reason"], "blocked")
        self.assertEqual((got["summary"], got["block"]["next"]), (SUMMARY, NEXT))
        self.assertEqual(got["counts"], {"act": 0, "check": 0, "tips": 0, "good": 0})
        self.assertEqual(got["products"], [], "nothing read from a page we could not check")
        [card] = got["cards"]
        self.assertEqual((card["kind"], card["title"]), ("unknown", f"{host}'s firewall stopped this check"))
        self.assertEqual(card["commands"], [MANUAL.format(host), "php -v"])
        self.assertEqual(card["firewalls"], firewalls)
        self.assertIn("It is not a problem with your site", card["means"])
        self.assertIn("firewalls often let a browser through and stop scripts", card["means"])
        self.assertIn("Run it from a machine the firewall lets through", card["advice"])
        texts = [s["text"] for s in card["saw"]]
        self.assertRegex(texts[0], rf"^We saw https://{re.escape(host)}/ answer {got['block']['status']} ")
        for mark in marks:
            self.assertIn(mark, texts)
        self.assertIn(f"Answered {got['block']['status']}", got["facts"])
        return card

    def test_the_three_corpus_shapes(self):
        for name, host, firewalls, marks in (
                ("cloudflare-challenge", "www.example.com", ["Cloudflare"],
                 ["We saw the header Cf-Mitigated: challenge", 'We saw the page title "Just a moment..."']),
                ("blocked-plain-403", "example.com", [], ["We saw the header Server: nginx"]),
                ("blocked-sucuri-503", "www.example.com", ["Sucuri"],
                 ['We saw the page title "Sucuri WebSite Firewall - Access Denied"',
                  "We saw the header X-Sucuri-Id: 11005"])):
            with self.subTest(name):
                case, net = case_net(name)
                card = self.assert_blocked(run(case["typed"], net), host, firewalls, marks)
                self.assertIn("a firewall or a server rule" if not firewalls
                              else f"{firewalls[0]} answered for your site", card["means"])

    def test_more_firewalls_by_their_own_marks(self):
        for page, firewalls, mark in (
                ((202, {"x-amzn-waf-action": "challenge", "x-amz-cf-id": "EXAMPLE=="}, b"<html></html>"),
                 ["AWS WAF", "CloudFront"], "We saw the header X-Amzn-Waf-Action: challenge"),
                ((403, {"Server": "AkamaiGHost"}, b"<html><title>Access Denied</title></html>"),
                 ["Akamai"], 'We saw the page title "Access Denied"'),
                ((503, {}, b"<html><title>Your access to this site has been limited by the site owner</title>"
                           b"<p>Generated by Wordfence</p></html>"),
                 ["Wordfence"], 'We saw "generated by wordfence" in the page'),
                ((429, {"x-iinfo": "1-2-3", "x-cdn": "Imperva"}, b"too many"),
                 ["Imperva"], "We saw the header X-Iinfo: 1-2-3")):
            with self.subTest(firewalls):
                self.assert_blocked(home(page), "www.example.com", firewalls, [mark])

    def test_a_password_and_a_site_that_is_down(self):
        got = home((401, {"WWW-Authenticate": 'Basic realm="staging"'}, b"401"))
        self.assertEqual((got["reason"], got["block"]["kind"]), ("blocked", "password"))
        self.assertEqual(got["summary"], "Your site asks for a password, so we can't see what it shows.")
        self.assertEqual(got["cards"][0]["commands"], ["php -v"])
        for page in ((503, {"Server": "nginx"}, b"<html>Service Unavailable</html>"),
                     (503, {"Server": "Sucuri/Cloudproxy", "X-Sucuri-ID": "11005"},
                      b"<title>Sucuri WebSite Firewall - Unable to connect to the backend</title>")):
            with self.subTest(page[1]):
                got = home(page)
                self.assertEqual((got["reason"], got["error"]), ("error", "the home page answered 503"))
                self.assertIsNone(got["block"])

    def test_one_request_and_its_own_name(self):
        net = Net(names={"www.example.com": [PUBLIC]}, pages={"https://www.example.com/": (
            403, {"cf-mitigated": "challenge"}, b"Just a moment...")})
        run("www.example.com", net)
        self.assertEqual(len(net.opened), 1, "no retry")
        self.assertTrue(net.opened[0]["agent"].startswith("php2shell-check/"), "never a disguised agent")

    def test_the_terminal_and_markdown_say_what_to_run(self):
        code, out, _ = fixture("cloudflare-challenge")
        self.assertEqual(code, 2, "could not check")
        self.assertIn("Your site's firewall stopped this check from this machine", out)
        self.assertIn("run it from a machine the firewall lets through", out)
        self.assertIn('  $ curl -sI https://www.example.com/ | grep -iE "server|x-powered-by"', out)
        self.assertIn("  $ php -v", out)
        self.assertIn("We saw the header Cf-Mitigated: challenge", out)
        self.assertNotIn("Could not check www.example.com:", out)
        case, net = case_net("cloudflare-challenge")
        md = p2s.markdown(run(case["typed"], net))
        self.assertIn(f"**{SUMMARY}**", md)
        self.assertIn("```sh\n" + MANUAL.format("www.example.com") + "\nphp -v\n```", md)


class Merge(unittest.TestCase):
    def test_the_same_server_on_two_hosts_is_one_card(self):
        """Skald 2.22.1: www and wp both send Server: nginx/1.24.0 (a headless WordPress)."""
        case, net = case_net("headless-wordpress-same-server-on-two-hosts")
        got = run(case["typed"], net)
        evidenced(self, got)
        tips = [c for c in got["cards"] if c["title"] == "Your server shows its exact version: nginx 1.24.0"]
        self.assertEqual(len(tips), 1, [c["title"] for c in got["cards"]])
        tip = tips[0]
        self.assertEqual(tip["hosts"], ["www.example.com", "wp.example.com"])
        self.assertEqual({p2s.host_of(s["url"]) for s in tip["saw"]}, {"www.example.com", "wp.example.com"},
                         "each host's evidence")
        self.assertTrue(tip["means"].endswith("Seen on 2 hosts: www.example.com and wp.example.com."))
        self.assertEqual(len({c["title"] for c in got["cards"]}), len(got["cards"]), "no title twice")
        self.assertEqual(got["counts"]["tips"], 3)
        self.assertIn("3 tips", got["summary"])

    def test_a_single_card_is_kept_as_it_was(self):
        one = {"kind": "tip", "group": "tips", "title": "A", "saw": [{"text": "x", "url": "https://a.example.com/"}],
               "means": "M.", "hosts": ["a.example.com"]}
        other = {**one, "title": "B"}
        self.assertEqual(p2s.merge([dict(one), dict(other)]), [one, other])
        got = p2s.merge([dict(one), {**one, "saw": [{"text": "x", "url": "https://a.example.com/"}]}])
        self.assertEqual((len(got), got[0]["means"], len(got[0]["saw"])), (1, "M.", 1))


